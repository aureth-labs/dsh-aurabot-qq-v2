import { dataDir, ensureDir } from '../../../../src/core/store/index.ts'
import { statSync, existsSync, readFileSync, writeFileSync, unlinkSync } from 'node:fs'
import { mimeOf } from '../../../../src/core/message/media/inspect.ts'
import { join } from 'node:path'

export function registerAvatarRoutes({ http, ROOT, log, bot }) {
  const { route, send, readBody } = http

  // 形象图
  // 头像：自定义的放在数据目录（重装插件不丢），没有就用插件自带的大肥鱼
  const AVATAR = () => dataDir('avatar.img')
  const avatarInfo = () => {
    try {
      return { custom: true, at: statSync(AVATAR()).mtimeMs }
    } catch (error) {
      return { custom: false, at: 0 }
    }
  }
  route('/avatar', async (req, res) => {
    if (existsSync(AVATAR())) {
      const buf = readFileSync(AVATAR())
      return send(res, 200, buf, mimeOf(buf))
    }
    const p = join(ROOT, 'assets', 'dafeiyu.jpg')
    if (!existsSync(p)) return send(res, 404, '')
    send(res, 200, readFileSync(p), 'image/jpeg')
  })
  route('/avatar/upload', async (req) => {
    const b = await readBody(req)
    const buf = Buffer.from(String(b.data || '').replace(/^data:[^,]+,/, ''), 'base64')
    if (!buf.length || buf.length > 5 * 1024 * 1024)
      return { ok: false, message: '图片太大（最多 5MB）或是空的' }
    if (!mimeOf(buf).startsWith('image/')) return { ok: false, message: '只支持 PNG、JPG、GIF、WebP 图片' }
    ensureDir(dataDir())
    writeFileSync(AVATAR(), buf)
    log.info('换了面板头像')
    return { ok: true, message: '头像换好了', avatar: avatarInfo() }
  })
  route('/avatar/reset', async () => {
    try {
      unlinkSync(AVATAR())
    } catch (error) {}
    return { ok: true, message: '恢复成默认头像了', avatar: avatarInfo() }
  })
  route('/avatar/sync-qq', async () => {
    const buf = existsSync(AVATAR())
      ? readFileSync(AVATAR())
      : readFileSync(join(ROOT, 'assets', 'dafeiyu.jpg'))
    try {
      await bot().internal('set_qq_avatar', { file: 'base64://' + buf.toString('base64') })
      return { ok: true, message: '已经设成机器人号的 QQ 头像' }
    } catch (error) {
      return { ok: false, message: 'QQ 头像没换成：' + error.message }
    }
  })
  return { avatarInfo }
}
